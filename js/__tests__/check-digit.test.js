describe('validateCheckDigit()', () => {
  it('throws error for non-string input', () => {
    expect(() => validateCheckDigit(123)).toThrow();
  });

  it('throws error for barcode with wrong length', () => {
    expect(() => validateCheckDigit('123')).toThrow();
  });

  it('throws error for non-numeric barcode', () => {
    expect(() => validateCheckDigit('a'.repeat(50))).toThrow();
  });

  describe('all 99 production barcodes', () => {
    it.each(BARCODE_FIXTURES)(
      'validates check digit for %s → DV=%d (%s)',
      (barcode, expectedDV, _fileName) => {
        const result = validateCheckDigit(barcode);
        expect(result.isValid).toBe(true);
        expect(result.calc).toBe(expectedDV);
        expect(result.expected).toBe(expectedDV);
      },
    );
  });

  describe('regression: tampered barcode', () => {
    it('rejects a barcode with flipped digit', () => {
      // Start from known-valid and flip one digit.
      const valid = '01350406260050601016040626005060101600000192845070';
      const tampered = valid.substring(0, 5) + '7' + valid.substring(6);
      const result = validateCheckDigit(tampered);
      expect(result.isValid).toBe(false);
      expect(result.calc).not.toBe(result.expected);
    });
  });
});
